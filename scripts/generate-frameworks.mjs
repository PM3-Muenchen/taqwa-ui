// Generates src/react.ts (@lit/react wrappers) and src/jsx.ts (React 19 JSX types) from custom-elements.json.
import { readFileSync, writeFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync('custom-elements.json', 'utf8'));
const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

const elements = manifest.modules
  .filter((mod) => /^src\/[^/]+\.ts$/.test(mod.path))
  .flatMap((mod) =>
    (mod.declarations ?? [])
      .filter((d) => d.customElement && d.tagName)
      .map((d) => ({
        module: `./${mod.path.slice(4, -3)}`,
        className: d.name,
        tagName: d.tagName,
        // `type` comes from the generic `emit(type, …)` helper, not a real event.
        events: [...new Set((d.events ?? []).map((e) => e.name).filter((name) => name && name !== 'type'))],
      })),
  )
  .sort((a, b) => a.tagName.localeCompare(b.tagName));

const imports = new Map();
for (const el of elements) imports.set(el.module, [...(imports.get(el.module) ?? []), el.className]);
const importLines = (typeOnly) =>
  [...imports].map(([mod, names]) => `import ${typeOnly ? 'type ' : ''}{ ${names.join(', ')} } from '${mod}';`).join('\n');

const header = '// Generated by scripts/generate-frameworks.mjs from custom-elements.json. Do not edit.\n';

writeFileSync(
  'src/react.ts',
  `${header}import * as React from 'react';
import { createComponent } from '@lit/react';
${importLines(false)}

${elements
  .map((el) => {
    const events = el.events.map((e) => `    on${pascal(e)}: '${e}',`).join('\n');
    return `export const ${el.className.replace(/^Taqwa/, '')} = createComponent({
  tagName: '${el.tagName}',
  elementClass: ${el.className},
  react: React,
  events: {${events ? `\n${events}\n  ` : ''}},
});`;
  })
  .join('\n\n')}
`,
);

writeFileSync(
  'src/jsx.ts',
  `${header}import type { HTMLAttributes, RefAttributes } from 'react';
${importLines(true)}

// React 19 sets these as properties: every public, non-method member the element adds to HTMLElement.
type ElementProps<E> = { [K in keyof E as K extends keyof HTMLElement ? never : E[K] extends Function ? never : K]?: E[K] };
type Props<E, V extends string> = Omit<HTMLAttributes<E>, keyof ElementProps<E>> &
  RefAttributes<E> &
  ElementProps<E> & { class?: string } & { [K in V as \`on\${K}\`]?: (event: CustomEvent) => void };

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${elements
  .map((el) => {
    const events = el.events.length ? el.events.map((e) => `'${e}'`).join(' | ') : 'never';
    return `      '${el.tagName}': Props<${el.className}, ${events}>;`;
  })
  .join('\n')}
    }
  }
}
`,
);

console.log(`Generated React wrappers and JSX types for ${elements.length} elements.`);
